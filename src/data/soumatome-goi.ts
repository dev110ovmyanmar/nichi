import type { CurriculumChapter, CurriculumSection } from "@/lib/jlpt/types"

/**
 * 8-week / 7-day shells modelled on 日本語総まとめ N2 語彙 (Ask Publishing).
 * Headwords and example sentences are OpenJLPT / JMdict / Tatoeba.
 * Placement uses Japanese stems — not English keyword leftovers.
 */

function day(
  weekId: string,
  number: number,
  titleJa: string,
  titleMy: string,
  introJa: string,
  introMy: string,
  stems: string[]
): CurriculumSection {
  return {
    id: `${weekId}-d${number}`,
    number,
    titleJa,
    titleMy,
    keywords: stems,
    introJa,
    introMy,
  }
}

function week(
  number: number,
  titleJa: string,
  titleMy: string,
  summaryMy: string,
  days: CurriculumSection[]
): CurriculumChapter {
  const id = `g${String(number).padStart(2, "0")}`
  return {
    id,
    book: "soumatome-goi",
    number,
    titleJa,
    titleMy,
    summaryMy,
    unitJa: "週",
    sectionUnitJa: "日目",
    sections: days,
  }
}

