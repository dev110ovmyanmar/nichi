import type { CurriculumChapter, CurriculumSection } from "@/lib/jlpt/types"

/**
 * 8-week / 7-day shells modelled on 日本語総まとめ N2 漢字 (Ask Publishing).
 * Kanji, 熟語, and example sentences are OpenJLPT / KANJIDIC2 / original
 * scene sentences — not copied from the textbook.
 */

function day(
  weekId: string,
  number: number,
  titleJa: string,
  titleMy: string,
  introJa: string,
  introMy: string
): CurriculumSection {
  return {
    id: `${weekId}-d${number}`,
    number,
    titleJa,
    titleMy,
    keywords: number === 7 ? [] : ["_study"],
    introJa,
    introMy,
  }
}

function week(
  number: number,
  titleJa: string,
  titleMy: string,
  summaryMy: string,
  radical: string,
  radicalMy: string,
  days: CurriculumSection[]
): CurriculumChapter {
  const id = `k${String(number).padStart(2, "0")}`
  return {
    id,
    book: "soumatome-kanji",
    number,
    titleJa,
    titleMy,
    summaryMy,
    radical,
    radicalMy,
    unitJa: "週",
    sectionUnitJa: "日目",
    sections: days,
  }
}

